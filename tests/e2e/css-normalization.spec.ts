import { expect, test } from '@playwright/test';
import { openSidebar, closeSidebar } from './support/sidebar';

const id = '10000000-0000-4000-8000-000000000002';
const longName = 'EspaceDeTravailAvecUnIntituleParticulierementLongSansSeparateurPourVerifierLeRedimensionnement';
const longEmail = 'collaborateur.longue.adresse@example-organisation-internationale.example.test';
for (const locale of ['fr', 'en'] as const) for (const theme of ['light', 'dark'] as const) for (const width of [375, 768, 1280]) {
 test(`CSS normalization (${locale}, ${theme}, ${width})`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1024 });
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: theme });
  await page.addInitScript((value) => { localStorage.setItem('locale', value.locale); localStorage.setItem('theme', value.theme); }, { locale, theme });
  let role: 'super_admin' | 'tenant_admin' | 'member' = 'super_admin';
  let anonymous = false;
  const fonts: string[] = [];
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('request', (request) => { if (request.resourceType() === 'font') fonts.push(request.url()); });
  await page.route('**/api/**', (route) => {
   const path = new URL(route.request().url()).pathname;
   const user = { id: 'css-fixture', name: 'Camille Martin', email: longEmail, emailVerified: true };
   const session = { id: 'css-session', userId: user.id, token: 'synthetic-css-session', createdAt: '2026-10-24T08:00:00Z', updatedAt: '2026-10-24T08:00:00Z', expiresAt: '2030-10-24T08:00:00Z', userAgent: longName };
   if (path === '/api/me') return route.fulfill({ status: anonymous ? 401 : 200, json: { user, access: { actorId: user.id, platformRole: role === 'super_admin' ? role : null, tenantRole: role === 'super_admin' ? null : role, tenantId: '10000000-0000-4000-8000-000000000001' } } });
   if (path === '/api/preferences') return route.fulfill({ json: { locale, theme } });
   if (path === '/api/auth/get-session') return route.fulfill({ json: anonymous ? null : { user, session } });
   if (path === '/api/auth/list-sessions') return route.fulfill({ json: [session] });
   if (path === '/api/auth/sign-in/email') return route.fulfill({ status: 401, json: { code: 'INVALID_EMAIL_OR_PASSWORD' } });
   if (path === '/api/platform/docs') return route.fulfill({ json: { fr: [], en: [] } });
   if (path === '/api/workspaces') return route.fulfill({ json: [{ id, tenant_id: '10000000-0000-4000-8000-000000000001', name: longName, visibility: 'tenant', color: '#b5a2df' }] });
   if (path === '/api/members') return route.fulfill({ json: [{ id: 'member', name: 'Camille Martin', email: longEmail, role: 'member' }] });
   return route.fulfill({ json: [] });
  });
  await page.goto('/docs');
  await page.getByRole('button', { name: 'Design system', exact: true }).click();
  await expect(page.locator('.ui-root')).toHaveCSS('font-family', /Lato/);
  await expect(page.getByRole('heading', { level: 1 })).toHaveCSS('font-size', '20px');
  await page.locator('.ui-gallery form').getByRole('button', { name: locale === 'fr' ? 'Enregistrer' : 'Save', exact: true }).click();
  const error = page.locator('.ui-field-error');
  await expect(error).toHaveText(locale === 'fr' ? 'Champ obligatoire.' : 'Required field.');
  await expect(error).toHaveCSS('color', theme === 'light' ? 'rgb(163, 41, 57)' : 'rgb(255, 177, 187)');
  const field = page.getByLabel(locale === 'fr' ? 'Nom de l’exemple' : 'Example name');
  await expect(field).toHaveAttribute('aria-invalid', 'true');
  await expect(field).toHaveCSS('font-family', /Lato/);
  await expect(field).toHaveCSS('font-size', '12px');
  await expect(page.locator('.ui-filter > .ui-field').first()).toHaveCSS('min-width', '0px');
  await expect(page.locator('.ui-filter > .ui-field').first()).toHaveCSS('flex-grow', '1');
  await page.screenshot({ path: info.outputPath('gallery-error.png'), fullPage: false });
  await page.locator('.ui-gallery .panel').last().scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('gallery-bottom.png'), fullPage: false });
  const native = await page.locator('.ui-gallery').evaluate((root) => {
   const textarea = document.createElement('textarea'); textarea.setAttribute('aria-label', 'CSS native textarea'); root.append(textarea);
   const code = document.createElement('code'); code.className = 'secret'; code.textContent = 'otpauth://totp/' + 'long-identifier'.repeat(30); root.append(code);
   const style = getComputedStyle(textarea);
   const result = { textareaResize: style.resize, textareaFont: style.fontFamily, textareaBoxSizing: style.boxSizing, textareaMinWidth: style.minWidth, codeWrap: getComputedStyle(code).whiteSpace, codeContained: code.scrollWidth <= code.clientWidth };
   textarea.remove(); code.remove(); return result;
  });
  expect(native.textareaResize).toBe('vertical');
  expect(native.textareaFont).toContain('Lato');
  expect(native.textareaBoxSizing).toBe('border-box');
  expect(native.codeWrap).toBe('pre-wrap');
  expect(native.codeContained).toBe(true);
  await openSidebar(page);
  await expect(page.locator('.ui-account summary')).toHaveCSS('display', 'list-item');
  await expect(page.locator('.ui-account summary')).not.toHaveCSS('list-style-type', 'none');
  await closeSidebar(page);
  role = 'tenant_admin';
  await page.goto('/app/profile');
  await expect(page.getByLabel(locale === 'fr' ? 'Email du compte' : 'Account email')).toHaveAttribute('readonly', '');
  await expect(page.getByRole('button', { name: locale === 'fr' ? 'Déconnecter mes autres appareils' : 'Sign out my other devices' })).toBeDisabled();
  await page.screenshot({ path: info.outputPath('profile-long.png'), fullPage: false });
  await page.goto('/app/members');
  await expect(page.getByRole('cell', { name: longEmail, exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('members-long.png'), fullPage: false });
  await page.goto('/app');
  const link = page.getByRole('link', { name: new RegExp(longName) });
  await expect(link).toHaveCSS('text-decoration-line', 'underline');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/app/invitations');
  await expect(page.getByRole('button', { name: locale === 'fr' ? 'Inviter' : 'Invite', exact: true })).toHaveCSS('font-family', /Lato/);
  await page.getByLabel(locale === 'fr' ? 'Adresse email' : 'Email address', { exact: true }).fill('invalid');
  await page.getByRole('button', { name: locale === 'fr' ? 'Inviter' : 'Invite', exact: true }).click();
  expect(await page.getByLabel(locale === 'fr' ? 'Adresse email' : 'Email address', { exact: true }).evaluate((element: HTMLInputElement) => element.validity.valid)).toBe(false);
  await page.screenshot({ path: info.outputPath('invitations.png'), fullPage: false });
  role = 'member';
  await page.goto('/app/invitations');
  await expect(page).toHaveURL(/\/403$/);
  anonymous = true;
  await page.goto('/login');
  const email = page.getByLabel(locale === 'fr' ? 'Adresse email' : 'Email address', { exact: true });
  const password = page.getByLabel(locale === 'fr' ? 'Mot de passe' : 'Password', { exact: true });
  await email.fill('css@example.test'); await email.focus(); await page.keyboard.press('Tab');
  await expect(password).toBeFocused();
  await expect(password).toHaveCSS('outline-style', 'solid');
  const focusPixels = await password.evaluate((element) => Number.parseFloat(getComputedStyle(element).outlineWidth) * window.devicePixelRatio);
  expect(focusPixels).toBeGreaterThan(1);
  await expect(password).toHaveCSS('font-family', /Lato/);
  await password.fill('synthetic-password-123');
  await page.getByRole('button', { name: locale === 'fr' ? 'Se connecter' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.locator('.ui-auth-brand')).toHaveCSS('line-height', '26.4px');
  await expect(page.locator('.auth-navigation a')).toHaveCSS('text-decoration-line', 'underline');
  await expect(page.getByRole('button', { name: locale === 'fr' ? 'Se connecter' : 'Sign in', exact: true })).toHaveCSS('transition-duration', '0s');
  await page.screenshot({ path: info.outputPath('auth-error-focus.png'), fullPage: false });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(fonts.length).toBeGreaterThan(0);
  expect(fonts.every((url) => new URL(url).origin === 'http://127.0.0.1:4173')).toBe(true);
  expect(errors).toEqual([]);
  await info.attach('native-styles', { body: JSON.stringify(native, null, 2), contentType: 'application/json' });
 });
}
